function measureText(text, isBold = false) {
    const metrics = isBold ? BOLD_METRICS : REG_METRICS;
    const defaultW = isBold ? 10.0 : 8.5;
    let w = 0;
    for (let i = 0; i < text.length; i++) {
        const ch = text[i];
        w += metrics[ch] || defaultW;
    }
    return w;
}

function wrapLines(text, maxWidth = 235.0, isBold = false) {
    if (!text) return [];
    const paragraphs = String(text).split('\n');
    const lines = [];
    for (const para of paragraphs) {
        const words = para.split(' ').filter(w => w.length > 0);
        let cur = '';
        for (const w of words) {
            const test = cur ? cur + ' ' + w : w;
            if (measureText(test, isBold) <= maxWidth) {
                cur = test;
            } else {
                if (cur) lines.push(cur);
                cur = w;
            }
        }
        if (cur) lines.push(cur);
    }
    return lines;
}

